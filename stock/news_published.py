def messages(date):
    if date != DATE:
        return []
    from collections import defaultdict
    from datetime import datetime, timedelta
    from news_summary import format_messages, validate
    pages = defaultdict(list)
    for page, title, what, why, how in ARTICLES:
        answer = {'complete': True, 'printed_date': DATE, 'articles': [
            {'title': title, 'kind': 'news', 'what': what, 'why': why, 'how': how}]}
        pages[page].extend(validate(answer, DATE, page))
    result, _ = format_messages(DATE, sorted(pages.items()))
    for i, message in enumerate(result):
        message['ts'] = (datetime.fromisoformat(PUBLISHED_AT) + timedelta(milliseconds=i)).isoformat(timespec='milliseconds')
    return result

PUBLISHED_AT = '2026-11-09T09:39:10+09:00'
